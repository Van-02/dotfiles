"""Implementar en Python el ejercicio anterior, es decir, leer dos numeros y 
determinar si son iguales, en caso afirmativo mostrar el mensaje 'Son iguales',
en caso negativo mostrar el mensaje 'No son iguales'
"""

a = int(input("Ingrese el primer numero: "))
b = int(input("Ingrese el segundo numero: "))

if a == b:
    print("Son iguales")
else:
    print("No son iguales")
