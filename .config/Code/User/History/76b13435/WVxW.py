"""
Leer dos numeros y determinar cual de ellos es el mayor, mostrando por pantalla 
"El valor mayor es: " y el correspondiente numero.
"""

a = int(input("Ingrese el primer numero: "))
b = int(input("Ingrese el segundo numero: "))

if a > b:
    print("El valor mayor es: ", a)
else:
    print("El valor mayor es: ", b)
